#!/usr/bin/env python3
"""Generate the flat documentation index for ``docs/``.

``docs/documentation-index.md`` is generated from the Markdown files that exist
in ``docs/``: their first heading is the title and their first plain paragraph
is the description. Nothing in it is hand-maintained, so it cannot drift from
the tree.

Usage::

    python scripts/docgen/doc_index.py           # write docs/documentation-index.md
    python scripts/docgen/doc_index.py --check   # fail when the file is stale
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

OUTPUT = Path("docs/documentation-index.md")
BANNER = (
    "<!-- generated by scripts/docgen/doc_index.py; do not edit by hand. -->\n"
    "<!-- Regenerate with `./run.sh docs-index`; `./run.sh docs` fails when stale. -->\n"
)

H1_RE = re.compile(r"^#\s+(.+?)\s*#*\s*$")
HEADING_RE = re.compile(r"^#{1,6}\s")
EMPHASIS_RE = re.compile(r"(\*\*|__|\*|_|`)")
SKIP_DESCRIPTION_PREFIXES = ("<!--", "|", ">", "-", "*", "#", "[!", "```", "<")


def repo_root() -> Path:
    result = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if result.returncode == 0 and result.stdout.strip():
        return Path(result.stdout.strip())
    return Path(__file__).resolve().parents[2]


def tracked_docs(root: Path) -> list[Path]:
    # Tracked plus new-but-not-ignored files, so a document can be indexed and
    # link-checked before it is committed.
    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "docs/*.md"],
        capture_output=True,
        check=True,
    )
    files = [root / name for name in result.stdout.decode().split("\0") if name]
    return sorted(path for path in files if path != root / OUTPUT)


def title_and_description(path: Path) -> tuple[str, str]:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return path.stem, ""
    title = ""
    description = ""
    in_fence = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence or not stripped:
            continue
        if not title and H1_RE.match(stripped):
            title = H1_RE.match(stripped).group(1).strip()
            continue
        if title and not description:
            if HEADING_RE.match(stripped) or stripped.startswith(SKIP_DESCRIPTION_PREFIXES):
                continue
            description = EMPHASIS_RE.sub("", stripped)
            if len(description) > 150:
                description = description[:147].rstrip() + "..."
    return title or path.stem, description


def section_of(path: Path, root: Path) -> str:
    relative = path.relative_to(root / "docs")
    if len(relative.parts) == 1:
        return "docs/"
    return "docs/" + "/".join(relative.parts[:-1]) + "/"


def render(root: Path) -> str:
    files = tracked_docs(root)
    by_section: dict[str, list[Path]] = {}
    for path in files:
        by_section.setdefault(section_of(path, root), []).append(path)

    sections = sorted(by_section, key=lambda name: (name != "docs/", name))
    out = [BANNER, "# Documentation index\n"]
    out.append(
        "Flat index of every long-lived Markdown document under `docs/`, generated from the\n"
        "files themselves. Titles come from each file's first heading and descriptions from its\n"
        "first paragraph, so this page is a view of the tree rather than a second place to\n"
        "maintain it. The curated entry points are in [`docs/README.md`](README.md).\n"
    )
    out.append(
        f"Totals: **{len(files)} documents** in **{len(sections)} sections** "
        f"(`python scripts/docgen/doc_index.py --check` verifies this page).\n"
    )
    out.append("| Section | Documents |\n| --- | --- |")
    for section in sections:
        target = section[len("docs/"):] or "./"
        out.append(f"| [`{section}`]({target}) | {len(by_section[section])} |")
    out.append("")
    for section in sections:
        out.append(f"## {section}\n")
        out.append("| Document | Title | Description |\n| --- | --- | --- |")
        for path in by_section[section]:
            title, description = title_and_description(path)
            link = path.relative_to(root / "docs").as_posix()
            description = description.replace("|", "\\|")
            title = title.replace("|", "\\|")
            out.append(f"| [`{link}`]({link}) | {title} | {description} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the index is stale")
    parser.add_argument("--root", default=None)
    args = parser.parse_args(argv)
    root = Path(args.root).resolve() if args.root else repo_root()
    target = root / OUTPUT
    rendered = render(root)
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            print(f"{OUTPUT} is stale; run `./run.sh docs-index`")
            return 1
        print(f"{OUTPUT} is current")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Render the measured gate numbers into one checked document.

Every number in ``docs/_generated/gate-metrics.md`` comes from artifacts that
``./run.sh`` writes while it runs the arms. Nothing in that page is typed by
hand, so a measurement cannot disagree with the document.

Inputs (all under ``.gate/``, all written by ``./run.sh``):

``timings.jsonl``   one JSON object per completed arm run (arm, argv, seconds, exit)
``junit.xml``       ``./run.sh test`` pytest report (counts and wall time)
``coverage.json``   ``./run.sh test`` coverage report
``debt.json``       ``./run.sh debt`` static-analysis counts

Usage::

    ./run.sh metrics            # rewrite docs/_generated/gate-metrics.md
    ./run.sh metrics --check    # fail when the document is stale
"""

from __future__ import annotations

import argparse
import json
import platform
import shlex
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

OUTPUT = Path("docs/_generated/gate-metrics.md")
BANNER = (
    "<!-- generated by scripts/docgen/gate_metrics.py from .gate/ artifacts; "
    "do not edit by hand. -->\n"
    "<!-- Refresh with `./run.sh metrics` after running the arms; "
    "`./run.sh metrics --check` fails when stale. -->\n"
)


def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def read_timings(path: Path) -> dict[str, dict]:
    """Last recorded run per arm."""
    latest: dict[str, dict] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return latest
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        latest[record.get("arm", "?")] = record
    return latest


def read_junit(path: Path) -> dict:
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError):
        return {}
    totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0, "seconds": 0.0}
    suites = [root] if root.tag == "testsuite" else root.findall("testsuite")
    for suite in suites:
        for key in ("tests", "failures", "errors", "skipped"):
            totals[key] += int(suite.get(key, 0) or 0)
        totals["seconds"] += float(suite.get("time", 0.0) or 0.0)
    return totals


def repo_relative(arg: str, root: Path) -> str:
    """Drop the repository prefix so a published command is portable."""
    prefix = f"{root}/"
    return arg.replace(prefix, "") if prefix in arg else arg


def fmt_seconds(value: float) -> str:
    return f"{value:.1f} s"


def render(gate_dir: Path) -> str:
    root = gate_dir.parent
    timings = read_timings(gate_dir / "timings.jsonl")
    junit = read_junit(gate_dir / "junit.xml")
    coverage = read_json(gate_dir / "coverage.json").get("totals", {})
    debt = read_json(gate_dir / "debt.json")
    environment = read_json(gate_dir / "env.json")

    lines = [BANNER, "# Gate metrics", ""]
    lines.append(
        "Measured numbers for `./run.sh` (the local gate). Every value below is read from an\n"
        "artifact under `.gate/` that the arm itself wrote, so re-running the arms and\n"
        "`./run.sh metrics` is the only way these numbers change."
    )
    lines.append("")
    lines.append("## Environment")
    lines.append("")
    lines.append("| Fact | Value |")
    lines.append("| --- | --- |")
    lines.append(
        f"| Host | `{environment.get('host', platform.system().lower() + '-' + platform.machine())}` |"
    )
    lines.append(f"| Python | `{environment.get('python', platform.python_version())}` |")
    lines.append(f"| uv | `{environment.get('uv', 'not recorded; run ./run.sh setup')}` |")
    lines.append("| Timing method | one run per arm, wall clock, cold cache not enforced |")
    lines.append("")

    lines.append("## Arms")
    lines.append("")
    lines.append("| Arm | Command | Wall time | Exit |")
    lines.append("| --- | --- | --- | --- |")
    if timings:
        for arm in sorted(timings):
            record = timings[arm]
            command = shlex.join(repo_relative(str(arg), root) for arg in record.get("argv", []))
            exit_code = record.get("exit", "?")
            status = "0" if exit_code == 0 else f"**{exit_code}**"
            lines.append(
                f"| `{arm}` | `{command}` | {fmt_seconds(float(record.get('seconds', 0.0)))} | {status} |"
            )
    else:
        lines.append("| — | no arm has been recorded yet: run `./run.sh <arm>` | — | — |")
    lines.append("")

    lines.append("## Test suite")
    lines.append("")
    if junit:
        lines.append("| Metric | Value |")
        lines.append("| --- | --- |")
        lines.append(f"| Tests collected | {junit['tests']} |")
        lines.append(f"| Failures | {junit['failures']} |")
        lines.append(f"| Errors | {junit['errors']} |")
        lines.append(f"| Skipped | {junit['skipped']} |")
        lines.append(f"| pytest wall time | {fmt_seconds(junit['seconds'])} |")
        if coverage:
            percent = coverage.get("percent_covered", 0.0)
            lines.append(f"| Coverage (`src/`) | {percent:.1f}% |")
            lines.append(
                f"| Statements / covered | {coverage.get('num_statements', 0)} / "
                f"{coverage.get('covered_lines', 0)} |"
            )
    else:
        lines.append("No pytest report yet: run `./run.sh test`.")
    lines.append("")

    lines.append("## Static-analysis debt")
    lines.append("")
    lines.append(
        "These counts are measured, not gated. `./run.sh lint` blocks only syntax and\n"
        "undefined-name errors; the wider style findings are recorded here so the debt is\n"
        "visible and cannot silently grow unnoticed."
    )
    lines.append("")
    if debt:
        lines.append("| Check | Command | Findings |")
        lines.append("| --- | --- | --- |")
        rows = [
            ("flake8 (all rules)", debt.get("flake8", {}).get("command"), debt.get("flake8", {}).get("count")),
            ("black --check", debt.get("black", {}).get("command"), debt.get("black", {}).get("count")),
            ("isort --check-only", debt.get("isort", {}).get("command"), debt.get("isort", {}).get("count")),
            ("mypy src/", debt.get("mypy", {}).get("command"), debt.get("mypy", {}).get("count")),
        ]
        for name, command, count in rows:
            rendered = "—" if count is None else str(count)
            lines.append(f"| {name} | `{command}` | {rendered} |")
    else:
        lines.append("No static-analysis report yet: run `./run.sh debt`.")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the document is stale")
    parser.add_argument("--root", default=None)
    args = parser.parse_args(argv)

    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[2]
    gate_dir = root / ".gate"
    target = root / OUTPUT
    rendered = render(gate_dir)

    if args.check:
        if not any(gate_dir.glob("*")):
            print(f"no {gate_dir.name}/ artifacts; nothing to compare {OUTPUT} against")
            return 0
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            print(f"{OUTPUT} is stale; run `./run.sh metrics`")
            return 1
        print(f"{OUTPUT} matches the recorded artifacts")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
